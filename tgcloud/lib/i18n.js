/** Translate `key` into `lang` (falls back to English, then Russian). */
export function t(lang, key, ...args) {
  const v = S[lang]?.[key] ?? S.en[key] ?? S.ru[key];
  if (v === undefined) return key;
  return typeof v === 'function' ? v(...args) : v;
}

/** The user's chosen language, else the one their Telegram app suggests. */
export async function userLang(userId, langCode = null) {
  const row = await db.get(sql`SELECT lang, lang_code FROM users WHERE id = ${userId}`);
  if (row && LANGS.includes(row.lang)) return row.lang;
  return detectLang(langCode || (row && row.lang_code));
}

/** A translate function bound to a user's language: `const T = await tr(id); T('key', ...)`. */
export async function tr(userId, langCode = null) {
  const lang = await userLang(userId, langCode);
  const T = (key, ...args) => t(lang, key, ...args);
  T.lang = lang;
  return T;
}

export async function hasChosenLang(userId) {
  const row = await db.get(sql`SELECT lang FROM users WHERE id = ${userId}`);
  return !!(row && LANGS.includes(row.lang));
}

export async function setUserLang(userId, lang) {
  await db.run(sql`UPDATE users SET lang = ${lang} WHERE id = ${userId}`);
}

