export const LANG_NAMES = {
  ru: '🇷🇺 Русский', en: '🇬🇧 English', ar: '🇸🇦 العربية', es: '🇪🇸 Español', pt: '🇧🇷 Português',
};

// Telegram app language -> our language. Ex-USSR languages default to Russian.
const RU_LIKE = ['ru', 'uk', 'be', 'kk', 'ky', 'uz', 'tg', 'hy', 'az', 'ka', 'tk', 'mo'];
export function detectLang(code) {
  const base = String(code || '').toLowerCase().split(/[-_]/)[0];
  if (LANGS.includes(base)) return base;
  if (RU_LIKE.includes(base)) return 'ru';
  return 'en';
}

